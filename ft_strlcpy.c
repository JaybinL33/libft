#include "libft.h"
#include <stddef.h>

size_t	ft_strlcpy(char *dst, const char *src, size_t size)
{
	size_t	i;

	if (!size)
		return (ft_strlen(src));
	i = 0;
	while (*src && i + 1 < size)
	{
		*dst++ = *src++;
		i++;
	}
	*dst = '\0';
	return (i + ft_strlen(src));
}
